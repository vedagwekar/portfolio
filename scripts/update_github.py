#!/usr/bin/env python3
"""Refresh js/github-data.js from GitHub's public contribution calendar + repo API.

Run from the project root:  python3 scripts/update_github.py
Private contributions only appear if "Include private contributions on my profile"
is enabled in GitHub's Contribution settings.
"""
import json, re, urllib.request, datetime, pathlib

USER = "vedagwekar"
OUT = pathlib.Path(__file__).resolve().parent.parent / "js" / "github-data.js"

def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "portfolio-updater"})
    return urllib.request.urlopen(req, timeout=20).read().decode()

html = get(f"https://github.com/users/{USER}/contributions")
cells = re.findall(r'data-date="([\d-]+)"[^>]*id="([^"]+)"', html)
tips = dict(re.findall(r'for="([^"]+)"[^>]*>([^<]+)</tool-tip>', html))
days = []
for date, cid in cells:
    m = re.match(r"(\d+) contribution", tips.get(cid, ""))
    days.append([date, int(m.group(1)) if m else 0])
days.sort()
total = sum(n for _, n in days)
head = re.search(r"([\d,]+)\s+contributions?\s+in the last year", html)
profile_total = int(head.group(1).replace(",", "")) if head else total
# keep a hand-entered (logged-in) total if it's higher than what the public page shows
old = re.search(r'"profileTotal": (\d+)', OUT.read_text()) if OUT.exists() else None
if old: profile_total = max(profile_total, int(old.group(1)))

repos = json.loads(get(f"https://api.github.com/users/{USER}/repos?per_page=100&sort=pushed"))
repo_list = [{"name": r["name"], "lang": r["language"], "desc": r["description"] or ""} for r in repos if not r["fork"]]

data = {"user": USER, "profileTotal": profile_total, "joined": "May 2025",
        "snapshot": datetime.date.today().isoformat(), "days": days, "repos": repo_list}
OUT.write_text(
    "// Generated by scripts/update_github.py. Repo list is also refreshed live in page.js.\n"
    "// profileTotal can be edited by hand if private contributions are hidden from the public calendar.\n"
    f"export const GITHUB = {json.dumps(data)};\n")
print(f"wrote {OUT.name}: {total} public contributions on the calendar, profileTotal={profile_total}")
